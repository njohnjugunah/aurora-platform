/**
 * Export Utilities
 * Handle CSV and PDF export functionality
 */

class ExportUtils {
    /**
     * Export data to CSV
     */
    static exportToCSV(data, filename = 'export.csv') {
        if (!data || data.length === 0) {
            Notifications.error('No data to export');
            return;
        }

        // Get headers from first row
        const headers = Object.keys(data[0]);

        // Create CSV content
        let csv = headers.map(h => `"${h}"`).join(',') + '\n';

        data.forEach(row => {
            const values = headers.map(header => {
                const value = row[header] ?? '';
                // Escape quotes in values
                const escaped = String(value).replace(/"/g, '""');
                return `"${escaped}"`;
            });
            csv += values.join(',') + '\n';
        });

        // Download
        this.downloadFile(csv, filename, 'text/csv');
        Notifications.success(`Report exported to ${filename}`);
    }

    /**
     * Export data to simple HTML table (for PDF conversion)
     */
    static exportToHTML(data, title = 'Report', metadata = {}) {
        if (!data || data.length === 0) {
            Notifications.error('No data to export');
            return;
        }

        const headers = Object.keys(data[0]);
        const timestamp = new Date().toLocaleString();

        let html = `
<!DOCTYPE html>
<html>
<head>
    <meta charset="utf-8">
    <title>${title}</title>
    <style>
        body {
            font-family: Arial, sans-serif;
            margin: 20px;
            color: #333;
        }
        h1 {
            color: #2c3e50;
            border-bottom: 2px solid #3498db;
            padding-bottom: 10px;
        }
        .metadata {
            margin-bottom: 20px;
            padding: 10px;
            background-color: #f5f5f5;
            border-left: 4px solid #3498db;
        }
        .metadata-item {
            margin: 5px 0;
            font-size: 0.9em;
        }
        .metadata-label {
            font-weight: bold;
            color: #2c3e50;
        }
        table {
            width: 100%;
            border-collapse: collapse;
            margin-top: 20px;
        }
        th {
            background-color: #34495e;
            color: white;
            padding: 12px;
            text-align: left;
            font-weight: bold;
        }
        td {
            padding: 10px 12px;
            border-bottom: 1px solid #ddd;
        }
        tr:nth-child(even) {
            background-color: #f9f9f9;
        }
        tr:hover {
            background-color: #f0f0f0;
        }
        .total-row {
            font-weight: bold;
            background-color: #ecf0f1;
            border-top: 2px solid #34495e;
        }
        .footer {
            margin-top: 20px;
            padding-top: 20px;
            border-top: 1px solid #ddd;
            font-size: 0.85em;
            color: #7f8c8d;
        }
    </style>
</head>
<body>
    <h1>${title}</h1>
    <div class="metadata">
        <div class="metadata-item"><span class="metadata-label">Generated:</span> ${timestamp}</div>
`;

        // Add metadata
        Object.entries(metadata).forEach(([key, value]) => {
            html += `<div class="metadata-item"><span class="metadata-label">${key}:</span> ${value}</div>\n`;
        });

        html += `
    </div>
    <table>
        <thead>
            <tr>
                ${headers.map(h => `<th>${h}</th>`).join('')}
            </tr>
        </thead>
        <tbody>
`;

        // Add data rows
        data.forEach(row => {
            html += '<tr>\n';
            headers.forEach(header => {
                const value = row[header] ?? '';
                html += `<td>${String(value).replace(/</g, '&lt;').replace(/>/g, '&gt;')}</td>\n`;
            });
            html += '</tr>\n';
        });

        html += `
        </tbody>
    </table>
    <div class="footer">
        <p>This report was generated by Aurora Platform</p>
    </div>
</body>
</html>
`;

        return html;
    }

    /**
     * Download file to browser
     */
    static downloadFile(content, filename, mimeType = 'text/plain') {
        const blob = new Blob([content], { type: mimeType });
        const url = URL.createObjectURL(blob);
        const link = document.createElement('a');
        link.href = url;
        link.download = filename;
        document.body.appendChild(link);
        link.click();
        document.body.removeChild(link);
        URL.revokeObjectURL(url);
    }

    /**
     * Print report
     */
    static printReport(html, title = 'Report') {
        const printWindow = window.open('', '', 'width=800,height=600');
        printWindow.document.write(html);
        printWindow.document.title = title;
        printWindow.document.close();

        // Wait for content to load before printing
        setTimeout(() => {
            printWindow.print();
        }, 500);
    }

    /**
     * Format number as currency (KES)
     */
    static formatCurrency(value) {
        return new Intl.NumberFormat('en-KE', {
            style: 'currency',
            currency: 'KES'
        }).format(value);
    }

    /**
     * Format date
     */
    static formatDate(dateString) {
        const date = new Date(dateString);
        return new Intl.DateTimeFormat('en-KE', {
            year: 'numeric',
            month: 'short',
            day: 'numeric'
        }).format(date);
    }

    /**
     * Format time
     */
    static formatTime(timeString) {
        const date = new Date(timeString);
        return new Intl.DateTimeFormat('en-KE', {
            hour: '2-digit',
            minute: '2-digit',
            second: '2-digit'
        }).format(date);
    }
}

window.ExportUtils = ExportUtils;
